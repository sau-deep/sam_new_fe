export const getStateOptions = (value) => {
  if (!value) return StateList;
  
  // If value is a string (state name), filter by text
  if (typeof value === 'string') {
    return StateList.filter(e => e.text === value);
  }
  
  // If value is a number (state code), filter by state_code
  if (typeof value === 'number') {
    return StateList.filter(e => e.state_code === value);
  }
  
  return StateList;
};

export const getDistrictOptions = (value) => DistrictList.filter(e => e.state_code === value);
export const getBlockOptions = (value) => BlockList.filter(e => e.district_code === value);
export const getVillageOptions = (value) => VillageList.filter(e => e.block_code === value);

// Helper functions to work with text values for better form integration
export const getDistrictOptionsByStateName = (stateName) => {
  const state = StateList.find(s => s.text === stateName);
  return state ? DistrictList.filter(d => d.state_code === state.state_code) : [];
};

export const getBlockOptionsByDistrictName = (stateName, districtName) => {
  const state = StateList.find(s => s.text === stateName);
  const district = DistrictList.find(d => d.text === districtName && d.state_code === state?.state_code);
  return district ? BlockList.filter(b => b.district_code === district.district_code) : [];
};

export const getVillageOptionsByBlockName = (stateName, districtName, blockName) => {
  const state = StateList.find(s => s.text === stateName);
  const district = DistrictList.find(d => d.text === districtName && d.state_code === state?.state_code);
  const block = BlockList.find(b => b.text === blockName && b.district_code === district?.district_code);
  return block ? VillageList.filter(v => v.block_code === block.block_code) : [];
}; 
